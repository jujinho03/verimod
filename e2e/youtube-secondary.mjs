import { chromium } from '@playwright/test'
const BASE = process.env.APP_URL ?? 'http://localhost:5190'
const browser = await chromium.launch()
const page = await browser.newPage()
try {
  await page.goto(`${BASE}/`)
  await page.getByRole('button', { name: '영상 댓글 일괄 분석' }).click()
  await page.locator('#content-url').fill('https://www.youtube.com/watch?v=dQw4w9WgXcQ')
  await page.getByRole('button', { name: '주소 확인' }).click()
  await page.getByRole('heading', { name: '이 영상이 맞나요?' }).waitFor({ timeout: 30000 })
  await page.getByRole('button', { name: '수집 범위 정하기' }).click()
  await page.getByRole('button', { name: '20개' }).click()
  await page.getByRole('switch', { name: /답글도 가져오기/ }).uncheck()
  await page.getByRole('button', { name: '댓글 가져오기' }).click()
  await page.locator('#kw').waitFor({ timeout: 60000 })
  await page.getByRole('button', { name: /일치한 .*개 고르기/ }).click()
  await page.getByRole('button', { name: /개로 계속/ }).click()
  await page.getByRole('button', { name: /개 판정 시작/ }).click()
  await page.locator('.vtiles').waitFor({ timeout: 120000 })
  await page.getByRole('button', { name: '영수증·공유' }).click()
  await page.locator('.vlinkrow__url').waitFor()
  const publicUrl = await page.locator('.vlinkrow__url').innerText()
  await page.getByRole('status').filter({ hasText: '온체인 등록 완료' }).waitFor({ timeout: 120000 })
  const ownerStatus = await page.getByRole('status').innerText()
  await page.goto(publicUrl)
  await page.getByRole('status').filter({ hasText: '온체인 등록 완료' }).waitFor({ timeout: 30000 })
  const publicStatus = await page.getByRole('status').innerText()
  console.log(`YOUTUBE_SECONDARY_PASS ${ownerStatus} | PUBLIC ${publicStatus}`)
} finally { await browser.close() }
